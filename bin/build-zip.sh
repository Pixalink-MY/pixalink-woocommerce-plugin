#!/usr/bin/env bash
#
# Build a distributable plugin zip.
#
#   bin/build-zip.sh [selfhosted|wporg|marketplace]      (or FLAVOUR=... bin/build-zip.sh)
#
# Flavours:
#   selfhosted   pixalink.io download: bundles yahnis-elsts/plugin-update-checker + src/Updates and adds
#                the "Update URI" header pointing at updates.pixalink.io.
#   wporg        WordPress.org directory: zero runtime Composer dependencies, no updater, no Update URI.
#   marketplace  WooCommerce Marketplace: same payload as wporg (Woo: header added at onboarding).
#
# Environment:
#   SKIP_JS_BUILD=1   reuse the existing build/ directory
#   SKIP_POT=1        keep the committed languages/*.pot instead of regenerating it
#   DIST_DIR=path     output directory (default: dist/)
#   KEEP_WORK=1       keep the unzipped staging directory (dist/.work-<flavour>/<slug>)
#
# Output: dist/pixalink-loyalty-for-woocommerce-<version>-<flavour>.zip and a matching .sha256 file.
set -euo pipefail

FLAVOUR="${1:-${FLAVOUR:-selfhosted}}"
case "$FLAVOUR" in
	selfhosted | wporg | marketplace) ;;
	*)
		echo "Unknown flavour '$FLAVOUR' (expected selfhosted, wporg or marketplace)." >&2
		exit 2
		;;
esac

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SLUG="pixalink-loyalty-for-woocommerce"
MAIN="$ROOT/$SLUG.php"
VERSION="$(sed -n 's/^[[:space:]]*\*[[:space:]]*Version:[[:space:]]*//p' "$MAIN" | head -n 1 | tr -d '[:space:]')"
DIST_DIR="${DIST_DIR:-$ROOT/dist}"
WORK="$DIST_DIR/.work-$FLAVOUR"
STAGE="$WORK/$SLUG"
ZIP_NAME="$SLUG-$VERSION-$FLAVOUR.zip"
UPDATE_URI="https://updates.pixalink.io/wp/$SLUG/"

if [ -z "$VERSION" ]; then
	echo "Cannot read the Version header from $MAIN." >&2
	exit 1
fi

echo "Building $SLUG $VERSION ($FLAVOUR)"

if [ "${SKIP_JS_BUILD:-0}" != "1" ]; then
	(cd "$ROOT" && npm run build --silent)
fi
if [ ! -f "$ROOT/build/blocks.asset.php" ]; then
	echo "build/ is missing; run npm run build first." >&2
	exit 1
fi

if [ "${SKIP_POT:-0}" != "1" ]; then
	"$ROOT/bin/make-pot.sh"
fi

rm -rf "$WORK"
mkdir -p "$STAGE"
rsync -a --exclude-from="$ROOT/.distignore" "$ROOT/" "$STAGE/"

if [ "$FLAVOUR" != "selfhosted" ]; then
	rm -rf "$STAGE/src/Updates"
fi

# Production autoloader. Only the self-hosted flavour gets a runtime dependency (the update checker).
cp "$ROOT/composer.json" "$ROOT/composer.lock" "$STAGE/"
(
	cd "$STAGE"
	if [ "$FLAVOUR" = "selfhosted" ]; then
		php -r '
			$file = "composer.json";
			$json = json_decode( file_get_contents( $file ), true );
			$constraint = $json["require-dev"]["yahnis-elsts/plugin-update-checker"] ?? "^5.6";
			$json["require"]["yahnis-elsts/plugin-update-checker"] = $constraint;
			unset( $json["require-dev"], $json["autoload-dev"], $json["scripts"], $json["scripts-descriptions"] );
			file_put_contents( $file, json_encode( $json, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES ) . "\n" );
		'
		composer update yahnis-elsts/plugin-update-checker --no-dev --no-interaction --no-progress --quiet --prefer-dist --classmap-authoritative
		test -f vendor/yahnis-elsts/plugin-update-checker/load-v5p7.php || test -d vendor/yahnis-elsts/plugin-update-checker
	else
		composer install --no-dev --no-interaction --no-progress --quiet --prefer-dist --classmap-authoritative
		if [ -n "$(find vendor -mindepth 1 -maxdepth 1 -type d ! -name composer)" ]; then
			echo "The $FLAVOUR build must not ship runtime Composer packages:" >&2
			find vendor -mindepth 1 -maxdepth 1 -type d ! -name composer >&2
			exit 1
		fi
	fi
	# Keep composer.json next to vendor/ (Plugin Check expects it); the lock file is build-only.
	rm -f composer.lock
)

if [ "$FLAVOUR" = "selfhosted" ]; then
	UPDATE_URI="$UPDATE_URI" perl -0pi -e 's/( \* Requires Plugins:[^\n]*\n)/$1 * Update URI:           $ENV{UPDATE_URI}\n/' "$STAGE/$SLUG.php"
	grep -q "Update URI:           $UPDATE_URI" "$STAGE/$SLUG.php" || {
		echo "Failed to add the Update URI header." >&2
		exit 1
	}
fi

COMMIT="$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"
BUILT_AT="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
cat >"$STAGE/build-info.php" <<PHP
<?php
/**
 * Generated by bin/build-zip.sh. Do not edit.
 *
 * @package Pixalink\Loyalty
 */

defined( 'ABSPATH' ) || exit;

return array(
	'distribution' => '$FLAVOUR',
	'version'      => '$VERSION',
	'commit'       => '$COMMIT',
	'built_at'     => '$BUILT_AT',
);
PHP

mkdir -p "$DIST_DIR"
rm -f "$DIST_DIR/$ZIP_NAME" "$DIST_DIR/$ZIP_NAME.sha256"
(cd "$WORK" && zip -rqX "$DIST_DIR/$ZIP_NAME" "$SLUG")

if command -v sha256sum >/dev/null 2>&1; then
	(cd "$DIST_DIR" && sha256sum "$ZIP_NAME" >"$ZIP_NAME.sha256")
else
	(cd "$DIST_DIR" && shasum -a 256 "$ZIP_NAME" >"$ZIP_NAME.sha256")
fi

if [ "${KEEP_WORK:-0}" != "1" ]; then
	rm -rf "$WORK"
fi

echo "$DIST_DIR/$ZIP_NAME"
